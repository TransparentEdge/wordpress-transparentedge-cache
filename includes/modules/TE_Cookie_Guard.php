<?php
/**
 * Cookie guard.
 *
 * Two jobs, both aimed at the single most common CDN miss cause — a stray
 * analytics/consent cookie forcing a pass on anonymous HTML:
 *
 *   1. A propose-only VCL snippet that strips every cookie EXCEPT a short
 *      allowlist before the cache lookup, so only cookies that genuinely vary
 *      the response survive. (The plugin never deploys VCL — it proposes it.)
 *   2. A runtime diagnostic that probes the origin and warns if it emits
 *      Set-Cookie on an anonymous page or a Vary that still mentions Cookie.
 *
 * The response-side Vary: Cookie fragmentation is already neutralised at the
 * origin by TE_Headers; this covers the request side (pass-on-cookie) and
 * surfaces anything the origin is still doing wrong.
 *
 * @package flavor_edge_cache
 */

namespace flavor_edge;

defined( 'ABSPATH' ) || exit;

class TE_Cookie_Guard {

	public static function init() {
		if ( is_admin() ) {
			add_action( 'wp_ajax_flavor_edge_probe_cookies', array( __CLASS__, 'ajax_probe' ) );
		}
	}

	/**
	 * Build the keep-list regex (cookie NAME alternation) from the plugin's
	 * excluded-cookies allowlist. Each entry is treated as a literal name
	 * prefix, so "wordpress_logged_in_" keeps "wordpress_logged_in_abc123".
	 *
	 * @param string[] $lines Allowlist entries.
	 * @return string PCRE alternation, or '(?!)' (matches nothing) when empty.
	 */
	public static function build_keep_regex( array $lines ) {
		$parts = array();
		foreach ( $lines as $line ) {
			$line = trim( $line );
			// Drop characters that are invalid in a cookie name and that would
			// break out of the VCL string / regex ( " \ ; and control chars ).
			$line = preg_replace( '/["\\\\;\x00-\x1f]/', '', (string) $line );
			if ( '' === $line ) {
				continue;
			}
			$parts[] = preg_quote( $line, '/' ) . '[^=]*';
		}
		if ( empty( $parts ) ) {
			return '(?!)';
		}
		return implode( '|', $parts );
	}

	/**
	 * Allowlist entries drawn from the plugin settings.
	 *
	 * @return string[]
	 */
	private static function allowlist() {
		$raw = (string) TE_Settings::get( 'excluded_cookies', '' );
		return array_values( array_filter( array_map( 'trim', explode( "\n", $raw ) ) ) );
	}

	/**
	 * Generate the propose-only cookie-normalisation VCL snippet.
	 *
	 * Uses the canonical, vendor-neutral Varnish "keep only whitelisted cookies"
	 * recipe (regsuball), so it is correct on any Varnish without assuming a
	 * specific vmod. Review before deploying from the Transparent Edge dashboard.
	 *
	 * @return string VCL.
	 */
	public static function generate_vcl_snippet() {
		$keep = self::build_keep_regex( self::allowlist() );

		$tpl = <<<'VCL'
# ── Cookie normalisation (anonymous cache-key hygiene) ──────────
# Generated by Transparent Edge Cache plugin — PROPOSE ONLY, review first.
#
# Strips every request cookie EXCEPT the allowlist below, before the cache
# lookup. A stray analytics/consent cookie (_ga, _fbp, CMP, Marfeel…) then no
# longer forces a pass on anonymous HTML. Cookies that genuinely personalise
# the response (login, cart) are kept, so those requests still bypass cache.
#
# Deploy this in: Configuration → VCL → vcl_recv
# ────────────────────────────────────────────────────────────────

sub vcl_recv {
    if (req.http.Cookie) {
        set req.http.Cookie = ";" + req.http.Cookie;
        set req.http.Cookie = regsuball(req.http.Cookie, "; +", ";");
        set req.http.Cookie = regsuball(req.http.Cookie, ";(__KEEP__)=", "; \1=");
        set req.http.Cookie = regsuball(req.http.Cookie, ";[^ ][^;]*", "");
        set req.http.Cookie = regsuball(req.http.Cookie, "^[; ]+|[; ]+$", "");
        if (req.http.Cookie == "") {
            unset req.http.Cookie;
        }
    }
}
VCL;

		return str_replace( '__KEEP__', $keep, $tpl );
	}

	/**
	 * Probe the origin anonymously and report cookie-related cacheability risks.
	 *
	 * @return array
	 */
	public static function probe() {
		$url = home_url( '/' );
		$res = wp_remote_get( $url, array(
			'timeout'     => 5,
			'redirection' => 0,
			'cookies'     => array(),
			'sslverify'   => false,
			'headers'     => array( 'User-Agent' => 'FlavorEdgeCache-CookieProbe/1.0' ),
		) );

		if ( is_wp_error( $res ) ) {
			return array( 'ok' => false, 'error' => $res->get_error_message() );
		}

		$status     = (int) wp_remote_retrieve_response_code( $res );
		$set_cookie = wp_remote_retrieve_header( $res, 'set-cookie' );
		$vary       = wp_remote_retrieve_header( $res, 'vary' );

		$cookie_names = array();
		foreach ( (array) $set_cookie as $sc ) {
			$name = trim( strtok( (string) $sc, '=' ) );
			if ( '' !== $name ) {
				$cookie_names[] = $name;
			}
		}

		$vary_cookie = is_string( $vary ) && preg_match( '/cookie/i', $vary );

		$warnings = array();
		if ( ! empty( $cookie_names ) ) {
			$warnings[] = sprintf(
				/* translators: %s: cookie names */
				__( 'The anonymous homepage sets a cookie (%s). Varnish will not store a response that carries Set-Cookie, so every hit becomes a miss. Find the plugin/theme setting it and stop it on anonymous requests.', 'flavor-edge-cache' ),
				implode( ', ', array_unique( $cookie_names ) )
			);
		}
		if ( $vary_cookie ) {
			$warnings[] = __( 'The origin still advertises Vary: Cookie. The plugin neutralises this at the edge-facing response, but the source (theme/plugin) is worth fixing too.', 'flavor-edge-cache' );
		}

		return array(
			'ok'          => true,
			'status'      => $status,
			'set_cookie'  => array_values( array_unique( $cookie_names ) ),
			'vary'        => is_string( $vary ) ? $vary : '',
			'vary_cookie' => (bool) $vary_cookie,
			'warnings'    => $warnings,
			'clean'       => empty( $warnings ),
		);
	}

	public static function ajax_probe() {
		check_ajax_referer( 'flavor_edge_admin', 'nonce' );
		if ( ! current_user_can( 'manage_options' ) ) {
			wp_send_json_error( 'Unauthorized' );
		}
		wp_send_json_success( self::probe() );
	}
}
